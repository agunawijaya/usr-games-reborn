/**
 * Bakes the showcase boards for the title screen, the Hall's attract loop and the poster: a few
 * rich 4×4 boards with a short, friendly hunt on each (common words, a long one to finish), so
 * those screens never load the dictionary. Words the repository's content guard would refuse
 * are skipped. `tsx scripts/make-attract.ts`
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CONTENT_RULES, TRADEMARK_RULES } from '../../../scripts/check-words';
import { loadDictionary } from '../src/dictionary/load';
import { dealBoard } from '../src/engine/deal';

const print = (line: string) => process.stdout.write(`${line}\n`);
const OUTPUT = fileURLToPath(new URL('../src/render/attract-boards.ts', import.meta.url));
const SEEDS = ['showcase-435', 'showcase-100', 'showcase-174', 'showcase-56'];
const WORDS_PER_BOARD = 18;

function allowed(word: string): boolean {
  return [...CONTENT_RULES, ...TRADEMARK_RULES].every((rule) => {
    rule.pattern.lastIndex = 0;
    return !rule.pattern.test(word);
  });
}

async function main() {
  const trie = await loadDictionary();
  const boards = SEEDS.map((seed) => {
    const deal = dealBoard(trie, { size: 4, rule: 'classic', seed, minLetters: 3 });
    const friendly = deal.words.filter((w) => w.tier <= 1 && w.word.length >= 4 && allowed(w.word));
    const finale = friendly.filter((w) => w.word.length >= 7).slice(0, 1);
    const rest = friendly
      .filter((w) => w.word.length <= 6)
      .sort((a, b) => a.word.length - b.word.length || (a.word < b.word ? -1 : 1))
      .filter((_, i) => i % 2 === 0)
      .slice(0, WORDS_PER_BOARD - finale.length);
    const words = [...rest, ...finale].map((w) => ({ word: w.word, path: w.path }));
    print(`${seed}: ${words.map((w) => w.word).join(' ')}`);
    return { cubeAt: deal.roll.cubeAt, faceUp: deal.roll.faceUp, words };
  });
  const body = boards
    .map(
      (board) => `  {
    cubeAt: [${board.cubeAt.join(', ')}],
    faceUp: [${board.faceUp.join(', ')}],
    words: [
${board.words.map((w) => `      { word: '${w.word}', path: [${w.path.join(', ')}] },`).join('\n')}
    ],
  },`,
    )
    .join('\n');
  writeFileSync(
    OUTPUT,
    `// Generated by scripts/make-attract.ts. Do not edit by hand; rerun the script instead.

/**
 * Showcase boards with a short hunt on each, for the title screen, the Hall's attract loop and
 * the poster: rolls of the 4×4 cube set (cube and face per cell) and words with their paths.
 */
export interface AttractBoard {
  cubeAt: readonly number[];
  faceUp: readonly number[];
  words: readonly { word: string; path: readonly number[] }[];
}

export const ATTRACT_BOARDS: readonly AttractBoard[] = [
${body}
];
`,
  );
}

void main();
