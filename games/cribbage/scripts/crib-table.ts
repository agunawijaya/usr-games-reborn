/**
 * Writes `src/engine/ai/crib-sums.ts`: the summed crib scores for every pair of ranks, suited
 * and offsuit, worked out by `computeCribSums`. Run it again only if the counter changes:
 * `pnpm --filter @usr-games/game-cribbage exec tsx scripts/crib-table.ts`.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { computeCribSums, CRIB_DEALS } from '../src/engine/ai/crib-odds';

const started = Date.now();
const { suited, offsuit } = computeCribSums();
const rows = (table: number[][]) => table.map((row) => `    [${row.join(', ')}],`).join('\n');

const source = `// Generated by scripts/crib-table.ts from the game's own counter; do not edit by hand.

/**
 * The sum of the crib scores over all ${CRIB_DEALS.toLocaleString('en')} ways the other two crib
 * cards and the starter can fall, for two cards of the given ranks (row = lower rank − 1,
 * column = higher rank − 1). Divide by ${CRIB_DEALS} for the average. Suited pairs of one rank
 * cannot exist and read 0.
 */
export const CRIB_SUMS: { readonly suited: readonly (readonly number[])[]; readonly offsuit: readonly (readonly number[])[] } = {
  suited: [
${rows(suited)}
  ],
  offsuit: [
${rows(offsuit)}
  ],
};
`;

const target = fileURLToPath(new URL('../src/engine/ai/crib-sums.ts', import.meta.url));
writeFileSync(target, source);
process.stdout.write(`wrote ${target} in ${((Date.now() - started) / 1000).toFixed(1)} s\n`);
